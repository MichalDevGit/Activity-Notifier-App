using ActivityNotifier.App.Services;
using ActivityNotifier.App.Ui;
using ActivityNotifier.Core.Options;
using ActivityNotifier.Core.Rules;
using ActivityNotifier.Core.Tracking;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Options;

namespace ActivityNotifier.App;

/// <summary>
/// Application entry point: allows only one running copy, builds the Generic Host (services, settings, logging),
/// runs the tray on the UI thread, and shuts everything down in order when the user clicks Exit.
/// </summary>
internal static class Program
{
    // "Local\" = one per Windows logon session, so each signed-in user can run their own copy.
    private const string SingleInstanceMutexName = @"Local\ActivityNotifier.SingleInstance";

    // How long background services get to finish on exit (e.g. record the last minute).
    private static readonly TimeSpan ShutdownTimeout = TimeSpan.FromSeconds(5);

    /// <summary>The first method Windows runs when the .exe starts.</summary>
    // WinForms requires the UI thread to be a Single-Threaded Apartment (COM threading model).
    // Main is NOT async on purpose: after an "await" the code could continue on another thread, but the mutex
    // must be released by the thread that took it, and WinForms must stay on this STA thread.
    [STAThread]
    private static void Main()
    {
        // initiallyOwned: true = "create it and take it". createdNew tells us whether we were first.
        using var mutex = new Mutex(initiallyOwned: true, SingleInstanceMutexName, out bool createdNew);
        if (!createdNew)
        {
            // Another copy owns the mutex. We do not own it, so we must not release it.
            MessageBox.Show("Activity Notifier is already running.", "Activity Notifier");
            return;
        }

        try
        {
            Run();
        }
        finally
        {
            mutex.ReleaseMutex();
        }
    }

    private static void Run()
    {
        // Generated by the WinForms SDK: high-DPI mode, visual styles, default font.
        ApplicationConfiguration.Initialize();

        using IHost host = BuildHost();

        // Starts both background services. ValidateOnStart runs here too: a bad appsettings.json value throws now.
        host.Start();

        try
        {
            Application.Run(host.Services.GetRequiredService<TrayApplicationContext>());
        }
        finally
        {
            // Graceful shutdown: cancel the services' tokens and wait for them to finish
            // (the aggregator records the unfinished minute). Blocking is fine here: the UI loop has already ended.
            host.StopAsync(ShutdownTimeout).GetAwaiter().GetResult();
        }
    }

    // The composition root: the one place that decides which concrete class is used for what.
    private static IHost BuildHost()
    {
        // ContentRootPath = the .exe folder, so appsettings.json is found no matter which folder the app is started from.
        HostApplicationBuilder builder = Host.CreateApplicationBuilder(
            new HostApplicationBuilderSettings { ContentRootPath = AppContext.BaseDirectory });

        AddValidatedOptions<TrackingOptions>(builder, TrackingOptions.SectionName);
        AddValidatedOptions<RulesOptions>(builder, RulesOptions.SectionName);

        // Singleton = one shared instance for the whole app (all threads use the same tracker, counters, engine).
        builder.Services.AddSingleton(TimeProvider.System);
        builder.Services.AddSingleton<InputCounters>();
        builder.Services.AddSingleton<ActivityTracker>();

        // Several registrations of the same interface: the engine receives all of them as IEnumerable<IActivityRule>.
        builder.Services.AddSingleton<IActivityRule, HydrationRule>();
        builder.Services.AddSingleton<IActivityRule, MicroBreakRule>();
        builder.Services.AddSingleton<IActivityRule, LongBreakRule>();
        builder.Services.AddSingleton<IActivityRule, FingersRule>();
        builder.Services.AddSingleton<RulesEngine>();

        // Hosted services are started by host.Start() and stopped by host.StopAsync().
        builder.Services.AddHostedService<MinuteAggregatorService>();
        builder.Services.AddHostedService<RulesService>();

        builder.Services.AddSingleton<TrayApplicationContext>();

        return builder.Build();
    }

    // Binds one appsettings.json section to an options class and checks its [Range] attributes at startup.
    // Core classes take the plain options object (not IOptions<T>), so Core does not depend on the Options library.
    private static void AddValidatedOptions<TOptions>(HostApplicationBuilder builder, string sectionName)
        where TOptions : class
    {
        builder.Services.AddOptions<TOptions>()
            .Bind(builder.Configuration.GetSection(sectionName))
            .ValidateDataAnnotations()
            .ValidateOnStart();

        builder.Services.AddSingleton(services => services.GetRequiredService<IOptions<TOptions>>().Value);
    }
}
